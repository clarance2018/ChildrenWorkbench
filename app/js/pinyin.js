/* 将文本转为带注音的 ruby HTML（仅一年级模式调用）；非汉字原样输出 */
function toRuby(text){
  if(!text) return "";
  let html = "";
  for(const ch of text){
    if(PINYIN_MAP[ch]){
      html += `<ruby>${ch}<rt>${PINYIN_MAP[ch]}</rt></ruby>`;
    } else {
      html += ch === "\n" ? "<br>" : ch.replace(/</g,"&lt;").replace(/>/g,"&gt;");
    }
  }
  return html;
}
function esc(s){ return String(s==null?"":s).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;"); }
